    public static String toTraditionalTaiwan(String text) {
        if (text == null || text.isEmpty()) return text == null ? "" : text;
        String out = text;
        if (Build.VERSION.SDK_INT >= 24) {
            try {
                out = Transliterator.getInstance("Simplified-Traditional").transliterate(out);
            } catch (Throwable ignored) {}
        }
        if (out.equals(text)) out = fallbackChars(out);
        for (Map.Entry<String, String> e : PHRASES.entrySet()) out = out.replace(e.getKey(), e.getValue());
        return out;
    }

    private static String fallbackChars(String s) {
        int n = Math.min(SIMPLIFIED.length(), TRADITIONAL.length());
        StringBuilder b = new StringBuilder(s.length());
        outer:
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            for (int j = 0; j < n; j++) {
                if (SIMPLIFIED.charAt(j) == c) {
                    b.append(TRADITIONAL.charAt(j));
                    continue outer;
                }
            }
            b.append(c);
        }
        return b.toString();
    }
